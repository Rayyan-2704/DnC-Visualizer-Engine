/* 
    gen.cpp - seeded generator for all 20 DAA input files.

    gen all    [--seeds FILE] [--small DIR] [--large DIR]   make cp01-cp10, im01-im10
    gen verify [--seeds FILE]                               re-make everything in memory and compare with the recorded hashes
    gen one <id> [--n N] [--seed S] [--out FILE]            make a single file (any size)

    Defaults (run from the repo root):  seeds = src/generator/seeds.txt, small = data/small, large = data/large
    Files smaller than 1,000,000 bytes go to the "small" folder (these are submitted)
    and the bigger ones go to "large" (regenerated by the Miss Anaum/TA).

    Coordinates are produced as INTEGERS in micro-units (1 unit = 1,000,000 micro-units) and printed with exact integer
    arithmetic, so no floating-point printing is involved and the bytes are identical on every machine.
*/

