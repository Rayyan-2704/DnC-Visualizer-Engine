static const uint64_t SMALL_LIMIT_BYTES = 1000000;  // smaller than 1 MB
static const int64_t MICRO = 1000000;
static const int64_t MAX_COORD = 1000000LL * MICRO;  // 10^6 units, in micro-units


// Sink: writes bytes to a file (or nowhere) while counting them and hashing them (FNV-1a 64).
// The hash is what lets us prove "same seed --> same file" without keeping the big files.
class Sink {
    FILE* f_ = nullptr;
    bool ok_ = true;
    std::vector<char> buf_;
    uint64_t bytes_ = 0;
    uint64_t hash_ = 14695981039346656037ULL;

public:
    explicit Sink(const std::string &path) {
        if (!path.empty()) {
            f_ = std::fopen(path.c_str(), "wb");
            ok_ = (f_ != nullptr);
        }

        buf_.reserve(1 << 20);
    }

    bool ok() const { return ok_; }

    void put(const char *s, size_t n) {
        for (size_t i = 0; i < n; i++) {
            hash_ ^= static_cast<unsigned char>(s[i]);
            hash_ *= 1099511628211ULL;
        }

        bytes_ += n;
        buf_.insert(buf_.end(), s, s + n);

        if (buf_.size() >= (1u << 20)) flush();
    }

    void putChar(char c) { put(&c, 1); }
    void putStr(const std::string &s) { put(s.data(), s.size()); }

    void putInt(int64_t v) {
        char tmp[32];
        int len = std::snprintf(tmp, sizeof tmp, "%lld", static_cast<long long>(v));
        put(tmp, static_cast<size_t>(len));
    }

    // v is in micro-units
    void putMicro(int64_t v) {
        char tmp[48];
        int len = std::snprintf(tmp, sizeof tmp, "%lld.%06lld", static_cast<long long>(v / MICRO), static_cast<long long>(v % MICRO));
        put(tmp, static_cast<size_t>(len));
    }

    void flush() {
        if (f_ && !buf_.empty()) std::fwrite(buf_.data(), 1, buf_.size(), f_);
        buf_.clear();
    }

    void close() {
        flush();
        if (f_) { 
            std::fclose(f_);
            f_ = nullptr;
        }
    }

    uint64_t bytes() const { return bytes_; }
    uint64_t hash() const { return hash_; }

    ~Sink() { close(); }
};


// Closest-pair generators. First line n, then n lines "x y".
static void genUniform(Sink &s, Rng &r, int64_t n, int64_t maxMicro) {
    s.putInt(n); s.putChar('\n');
    
    for (int64_t i = 0; i < n; i++) {
        int64_t x = static_cast<int64_t>(r.below(static_cast<uint64_t>(maxMicro) + 1));
        int64_t y = static_cast<int64_t>(r.below(static_cast<uint64_t>(maxMicro) + 1));
        s.putMicro(x); s.putChar(' '); s.putMicro(y); s.putChar('\n');
    }
}


// 10 random centers; each point picks a center and adds a bell-shaped offset made from the sum of 4 uniform numbers.
static void genClustered(Sink &s, Rng &r, int64_t n) {
    const int K = 10;
    const int64_t spread = 10000 * MICRO;

    int64_t cx[K], cy[K];
    for (int c = 0; c < K; c++) {
        cx[c] = static_cast<int64_t>(r.below(MAX_COORD + 1));
        cy[c] = static_cast<int64_t>(r.below(MAX_COORD + 1));
    }

    s.putInt(n); s.putChar('\n');
    for (int64_t i = 0; i < n; i++) {
        int c = static_cast<int>(r.below(K));
        int64_t dx = 0, dy = 0;

        for (int k = 0; k < 4; k++)
            dx += r.range(-spread, spread);

        for (int k = 0; k < 4; k++)
            dy += r.range(-spread, spread);

        int64_t x = std::min(std::max(cx[c] + dx, int64_t(0)), MAX_COORD);
        int64_t y = std::min(std::max(cy[c] + dy, int64_t(0)), MAX_COORD);

        s.putMicro(x); s.putChar(' '); s.putMicro(y); s.putChar('\n');
    }
}


// Integer coordinates in [0, 1000]: about 1e6 possible spots, so many exact duplicates.
static void genDuplicates(Sink &s, Rng &r, int64_t n) {
    s.putInt(n); s.putChar('\n');

    for (int64_t i = 0; i < n; i++) {
        int64_t x = static_cast<int64_t>(r.below(1001));
        int64_t y = static_cast<int64_t>(r.below(1001));
        s.putInt(x); s.putChar(' '); s.putInt(y); s.putChar('\n');
    }
}


// Every point has the same x, only y varies.
static void genVerticalLine(Sink &s, Rng &r, int64_t n) {
    int64_t x0 = static_cast<int64_t>(r.below(MAX_COORD + 1));
    s.putInt(n); s.putChar('\n');

    for (int64_t i = 0; i < n; i++) {
        int64_t y = static_cast<int64_t>(r.below(MAX_COORD + 1));
        s.putMicro(x0); s.putChar(' '); s.putMicro(y); s.putChar('\n');
    }
}


// Equally spaced grid (first n cells, row by row), then shuffled so the file is not sorted.
static void genGrid(Sink &s, Rng &r, int64_t n) {
    int64_t cols = 1;
    while (cols * cols < n)
        ++cols;

    int64_t spacing = 1000000 / cols;
    std::vector<int64_t> cells(static_cast<size_t>(n));
    for (int64_t i = 0; i < n; i++)
        cells[static_cast<size_t>(i)] = i;

    shuffleVec(r, cells);
    s.putInt(n); s.putChar('\n');
    for (int64_t k : cells) {
        s.putInt((k % cols) * spacing); s.putChar(' ');
        s.putInt((k / cols) * spacing); s.putChar('\n');
    }
}


// n-2 random points, plus one planted pair only 0.000002 apart.
// Closest pair placed across the middle dividing line
static bool genStraddle(Sink &s, Rng &r, int64_t n, std::string &note) {
    if (n < 4) {
        note = "cp09 needs n >= 4";
        return false;
    }

    struct P { int64_t x, y; };

    std::vector<P> a(static_cast<size_t>(n - 2));
    for (auto &p : a) {
        p.x = static_cast<int64_t>(r.below(MAX_COORD + 1));
        p.y = static_cast<int64_t>(r.below(MAX_COORD + 1));
    }

    std::sort(a.begin(), a.end(), [](const P &u, const P &v) { return u.x < v.x || (u.x == v.x && u.y < v.y); });
    int64_t mid = n / 2;
    int64_t L = a[static_cast<size_t>(mid - 2)].x, R = a[static_cast<size_t>(mid - 1)].x;

    if (R - L < 8) { 
        note = "gap too small for the planted pair; choose another seed"; 
        return false; 
    }

    int64_t gm = L + (R - L) / 2;
    int64_t y0 = static_cast<int64_t>(r.below(MAX_COORD + 1));

    P p{gm - 1, y0}, q{gm + 1, y0};
    a.insert(a.begin() + (mid - 1), {p, q});
    shuffleVec(r, a);
    s.putInt(n); s.putChar('\n');

    for (const P &t : a) { 
        s.putMicro(t.x); s.putChar(' '); 
        s.putMicro(t.y); s.putChar('\n');
    }

    note = "planted pair is 0.000002 apart, across the middle dividing line";
    return true;
}


// Integer-multiplication generators. Two lines, one non-negative integer each.
static void numRandom(Sink &s, Rng &r, int64_t len) {
    std::string t(static_cast<size_t>(len), '0');
    t[0] = static_cast<char>('1' + r.below(9));  // no leading zero
    
    for (size_t i = 1; i < t.size(); i++)
        t[i] = static_cast<char>('0' + r.below(10));

    t += '\n';
    s.putStr(t);
}


// about 90% zeros
static void numSparse(Sink &s, Rng &r, int64_t len) {
    std::string t(static_cast<size_t>(len), '0');
    t[0] = static_cast<char>('1' + r.below(9));

    for (size_t i = 1; i < t.size(); i++) {
        if (r.below(10) == 0)
            t[i] = static_cast<char>('1' + r.below(9));
    }

    t += '\n';
    s.putStr(t);
}


// All 9's
static void numNines(Sink &s, int64_t len) {
    s.putStr(std::string(static_cast<size_t>(len), '9') + "\n");
}


// 10^(len-1) has exactly len digits
static void numPowerOfTen(Sink &s, int64_t len) {
    std::string t(static_cast<size_t>(len), '0');
    t[0] = '1';
    s.putStr(t + "\n");
}


// Number is zero
static void numZero(Sink &s) { 
    s.putStr("0\n"); 
}


// The 20 files: id, default seed, default size (points or digits), description.
struct Spec { const char *id; uint64_t seed; int64_t n; const char *desc; };
static const Spec SPECS[] = {
    {"cp01", 1001, 1000,    "uniform random reals in [0,1e6]"},
    {"cp02", 1002, 10000,   "uniform random reals in [0,1e6]"},
    {"cp03", 1003, 100000,  "uniform random reals in [0,1e6]"},
    {"cp04", 1004, 1000000, "uniform random reals in [0,1e6]"},
    {"cp05", 1005, 1000000, "clustered around 10 random centers"},
    {"cp06", 1006, 1000000, "integer coords in [0,1000], many duplicate points (distance 0)"},
    {"cp07", 1007, 100000,  "all points on one vertical line"},
    {"cp08", 1008, 100000,  "equally spaced grid (shuffled), many tied closest pairs"},
    {"cp09", 1009, 1000000, "closest pair straddles the middle dividing line"},
    {"cp10", 1010, 101,     "small file for step-by-step trace (coords in [0,1000])"},
    {"im01", 2001, 1000,    "two random numbers, n digits each"},
    {"im02", 2002, 10000,   "two random numbers, n digits each"},
    {"im03", 2003, 100000,  "two random numbers, n digits each"},
    {"im04", 2004, 1000000, "two random numbers, n digits each"},
    {"im05", 2005, 1000000, "unbalanced: n digits x 10 digits"},
    {"im06", 2006, 100000,  "first number is all 9s, second random, n digits each"},
    {"im07", 2007, 99999,   "odd length, about 90% zero digits, n digits each"},
    {"im08", 2008, 1000000, "both numbers are 10^(n-1) (powers of 10)"},
    {"im09", 2009, 1000000, "first number is 0, second has n digits"},
    {"im10", 2010, 101,     "small file for step-by-step trace, n digits each"},
};

static const int NUM_SPECS = static_cast<int>(sizeof(SPECS) / sizeof(SPECS[0]));
static const Spec* findSpec(const std::string &id) {
    for (const Spec &sp : SPECS) if (id == sp.id) return &sp;
    return nullptr;
}


// Writes the file for 'id' into 's'. Returns false on bad parameters.
static bool generate(const std::string &id, int64_t n, uint64_t seed, Sink &s, std::string &note) {
    if (n < 1) { 
        note = "size must be at least 1"; 
        return false; 
    }

    Rng r(seed);
    if (id == "cp01" || id == "cp02" || id == "cp03" || id == "cp04") genUniform(s, r, n, MAX_COORD);
    else if (id == "cp05") genClustered(s, r, n);
    else if (id == "cp06") genDuplicates(s, r, n);
    else if (id == "cp07") genVerticalLine(s, r, n);
    else if (id == "cp08") genGrid(s, r, n);
    else if (id == "cp09") return genStraddle(s, r, n, note);
    else if (id == "cp10") genUniform(s, r, n, 1000 * MICRO);

    else if (id == "im01" || id == "im02" || id == "im03" || id == "im04" || id == "im10") { numRandom(s, r, n); numRandom(s, r, n); }
    else if (id == "im05") { numRandom(s, r, n); numRandom(s, r, 10); }
    else if (id == "im06") { numNines(s, n); numRandom(s, r, n); }
    else if (id == "im07") { numSparse(s, r, n); numSparse(s, r, n); }
    else if (id == "im08") { numPowerOfTen(s, n); numPowerOfTen(s, n); }
    else if (id == "im09") { numZero(s); numRandom(s, r, n); }
    else {
        note = "unknown id: " + id;
        return false;
    }

    return true;
}


// seeds.txt: one line per file: id seed n bytes fnv1a64(hex) description
struct Row { std::string id; uint64_t seed = 0; int64_t n = 0; uint64_t bytes = 0; uint64_t hash = 0; std::string desc; };
static bool writeSeeds(const std::string &path, const std::vector<Row> &rows) {
    fs::path p(path);
    if (p.has_parent_path()) fs::create_directories(p.parent_path());

    FILE* f = std::fopen(path.c_str(), "wb");
    if (!f) 
        return false;

    std::fprintf(f, "# DAA project - recorded seeds and fingerprints of the 20 input files.\n");
    std::fprintf(f, "# Regenerate everything with:  bin\\gen.exe all      Check reproducibility with:  bin\\gen.exe verify\n");
    std::fprintf(f, "# RNG: std::mt19937_64(seed) with our own bits-to-range mapping (src/generator/rng.h).\n");
    std::fprintf(f, "# size = number of points (cp) or digits per number (im; im05 = digits of the long number).\n");
    std::fprintf(f, "# hash = FNV-1a 64-bit of the exact file bytes (LF line endings).\n");
    std::fprintf(f, "# id    seed   size      bytes      hash              description\n");

    for (const Row &r : rows) {
        std::fprintf(f, "%-5s %-6llu %-9lld %-10llu %016llx  %s\n", r.id.c_str(), static_cast<unsigned long long>(r.seed),
                     static_cast<long long>(r.n), static_cast<unsigned long long>(r.bytes),
                     static_cast<unsigned long long>(r.hash), r.desc.c_str());
    }   

    std::fclose(f);
    return true;
}


static bool readSeeds(const std::string &path, std::vector<Row> &rows) {
    std::ifstream in(path, std::ios::binary);
    if (!in)
        return false;

    std::string line;
    while (std::getline(in, line)) {
        if (!line.empty() && line.back() == '\r')
            line.pop_back();
        if (line.empty() || line[0] == '#')
            continue;

        std::istringstream ss(line);
        Row r;
        std::string hex;
        long long n = 0; unsigned long long seed = 0, bytes = 0;
        if (!(ss >> r.id >> seed >> n >> bytes >> hex))
            continue;

        r.seed = seed; r.n = n; r.bytes = bytes; r.hash = std::strtoull(hex.c_str(), nullptr, 16);
        std::getline(ss, r.desc);
        size_t k = r.desc.find_first_not_of(' ');
        r.desc = (k == std::string::npos) ? "" : r.desc.substr(k);
        rows.push_back(r);
    }

    return true;
}


// Commands
struct Opts {
    std::string seeds = "src/generator/seeds.txt", smallDir = "data/small", largeDir = "data/large", out;
    bool hasN = false, hasSeed = false;
    int64_t n = 0; uint64_t seed = 0;
};

static double nowMs() {
    using namespace std::chrono;
    return duration<double, std::milli>(steady_clock::now().time_since_epoch()).count();
}


static int cmdAll(const Opts &o) {
    fs::create_directories(o.smallDir);
    fs::create_directories(o.largeDir);
    std::vector<Row> rows;

    for (int i = 0; i < NUM_SPECS; i++) {
        const Spec& sp = SPECS[i];
        std::string tmp = (fs::path(o.largeDir) / (std::string(sp.id) + ".txt")).string();
        double t0 = nowMs();
        std::string note;
        Row row; row.id = sp.id; row.seed = sp.seed; row.n = sp.n; row.desc = sp.desc;
        {
            Sink s(tmp);
            if (!s.ok()) { 
                std::fprintf(stderr, "cannot write %s\n", tmp.c_str()); 
                return 1; 
            }

            if (!generate(sp.id, sp.n, sp.seed, s, note)) { 
                std::fprintf(stderr, "%s: %s\n", sp.id, note.c_str()); 
                return 1; 
            }

            s.close();
            row.bytes = s.bytes(); row.hash = s.hash();
        }

        bool small = row.bytes < SMALL_LIMIT_BYTES;
        fs::path smallPath = fs::path(o.smallDir) / (std::string(sp.id) + ".txt");
        if (small) {
            std::error_code ec;
            fs::remove(smallPath, ec);
            fs::copy_file(tmp, smallPath, ec);
            if (ec) { 
                std::fprintf(stderr, "cannot move %s: %s\n", tmp.c_str(), ec.message().c_str());
                return 1;
            }
            fs::remove(tmp, ec);
        }
        else {
            std::error_code ec;
            fs::remove(smallPath, ec);
        }
        
        std::printf("%-5s %10llu bytes -> %-10s %8.0f ms  %s\n", sp.id, static_cast<unsigned long long>(row.bytes), small ? "small" : "large", nowMs() - t0, note.c_str());
        rows.push_back(row);
    }

    if (!writeSeeds(o.seeds, rows)) { 
        std::fprintf(stderr, "cannot write %s\n", o.seeds.c_str()); 
        return 1; 
    }

    std::printf("Wrote %s\n", o.seeds.c_str());
    return 0;
}


static int cmdVerify(const Opts &o) {
    std::vector<Row> rows;
    if (!readSeeds(o.seeds, rows) || rows.empty()) { 
        std::fprintf(stderr, "cannot read %s\n", o.seeds.c_str()); 
        return 1; 
    }

    int bad = 0;
    for (const Row &r : rows) {
        const Spec *sp = findSpec(r.id);
        if (!sp) { 
            std::printf("%-5s MISMATCH  unknown id\n", r.id.c_str()); 
            bad++; 
            continue; 
        }

        Sink s("");  // hash only
        std::string note;
        bool ok = generate(r.id, r.n, r.seed, s, note) && s.bytes() == r.bytes && s.hash() == r.hash;
        std::printf("%-5s %s  seed=%llu size=%lld bytes=%llu hash=%016llx\n", r.id.c_str(), ok ? "OK      " : "MISMATCH",
                    static_cast<unsigned long long>(r.seed), static_cast<long long>(r.n),
                    static_cast<unsigned long long>(s.bytes()), static_cast<unsigned long long>(s.hash()));

        if (!ok)
            bad++;
    }

    if (bad == 0) 
        std::printf("ALL %zu FILES REPRODUCE EXACTLY\n", rows.size());
    else 
        std::printf("%d FILE(S) DO NOT MATCH\n", bad);

    return (bad == 0) ? 0 : 1;
}


static int cmdOne(const std::string &id, const Opts &o) {
    const Spec *sp = findSpec(id);
    if (!sp) { 
        std::fprintf(stderr, "unknown id '%s' (use cp01..cp10 or im01..im10)\n", id.c_str()); 
        return 1; 
    }

    int64_t n = o.hasN ? o.n : sp->n;
    uint64_t seed = o.hasSeed ? o.seed : sp->seed;
    std::string out = o.out.empty() ? id + ".txt" : o.out;
    Sink s(out);
    if (!s.ok()) { 
        std::fprintf(stderr, "cannot write %s\n", out.c_str()); 
        return 1; 
    }

    std::string note;
    if (!generate(id, n, seed, s, note)) { 
        std::fprintf(stderr, "%s\n", note.c_str()); 
        return 1; 
    }

    s.close();
    std::printf("%s: size=%lld seed=%llu -> %s (%llu bytes, hash %016llx) %s\n", id.c_str(), static_cast<long long>(n),
                static_cast<unsigned long long>(seed), out.c_str(), static_cast<unsigned long long>(s.bytes()),
                static_cast<unsigned long long>(s.hash()), note.c_str());
    
    return 0;
}


static void usage() {
    std::puts("usage:\n  gen all    [--seeds FILE] [--small DIR] [--large DIR]\n  gen verify [--seeds FILE]\n"
              "  gen one <id> [--n N] [--seed S] [--out FILE]");
}

int main(int argc, char **argv) {
    if (argc < 2) { 
        usage(); 
        return 1; 
    }

    std::string cmd = argv[1], id;
    Opts o;
    int i = 2;
    if (cmd == "one") {
        if (argc < 3) { 
            usage(); 
            return 1; 
        }

        id = argv[2]; i = 3;
    }

    for (; i < argc; i++) {
        std::string a = argv[i];
        auto val = [&](std::string &dst) { if (i + 1 >= argc) { usage(); std::exit(1); } dst = argv[++i]; };
        std::string tmp;

        if (a == "--seeds") val(o.seeds);
        else if (a == "--small") val(o.smallDir);
        else if (a == "--large") val(o.largeDir);
        else if (a == "--out") val(o.out);
        else if (a == "--n") { 
            val(tmp); o.n = std::atoll(tmp.c_str()); 
            o.hasN = true; 
        }
        else if (a == "--seed") { 
            val(tmp); o.seed = std::strtoull(tmp.c_str(), nullptr, 10); 
            o.hasSeed = true; 
        }
        else { 
            std::fprintf(stderr, "unknown option %s\n", a.c_str()); 
            usage(); 
            return 1; 
        }
    }

    if (cmd == "all") return cmdAll(o);
    if (cmd == "verify") return cmdVerify(o);
    if (cmd == "one") return cmdOne(id, o);

    usage();
    return 1;
}